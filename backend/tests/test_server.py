def chunk(delta, finish=None):
    return "data: " + json.dumps({"choices": [{"index": 0, "delta": delta, "finish_reason": finish}]}) + "\n\n"


def reply(*parts, call=None):
    """A streamed chat completion: one SSE event per text part, optionally ending in one tool call."""
    body = "".join(chunk({"content": part}) for part in parts)
    if call:
        name, arguments, identifier = call
        body += chunk({"tool_calls": [{"index": 0, "id": identifier, "type": "function",
                                       "function": {"name": name, "arguments": json.dumps(arguments)}}]})
    body += chunk({}, "tool_calls" if call else "stop") + "data: [DONE]\n\n"
    return httpx.Response(200, headers={"content-type": "text/event-stream"}, text=body)


class Stream:
    """The SSE connection of a test client: collects events, waits for one."""

    def __init__(self, client):
        self.client, self.events = client, []

    async def __aenter__(self):
        self.response = await self.client.get(f"{API}/events?token={TOKEN}")
        assert self.response.status == 200
        self.task = asyncio.create_task(self.pump())
        await self.wait(lambda e: e["type"] == "hello")
        return self

    async def __aexit__(self, *exc):
        self.task.cancel()
        self.response.close()

    async def pump(self):
        async for raw in self.response.content:
            line = raw.decode()
            if line.startswith("data: "):
                self.events.append(json.loads(line[6:]))

    async def wait(self, predicate, after=0):
        async with asyncio.timeout(5):
            while True:
                for event in self.events[after:]:
                    if predicate(event):
                        return event
                await asyncio.sleep(0.01)

    def of(self, kind):
        return [e for e in self.events if e["type"] == kind]


class Env:
    def __init__(self, http, service, script, requests):
        self.http, self.service, self.script, self.requests = http, service, script, requests

    async def call(self, method, path, body=None, status=200):
        response = await self.http.request(method, API + path, **({"json": body} if body is not None else {}))
        data = await response.json()
        assert response.status == status, data
        return data

    async def lesson(self):
        course = await self.call("POST", "/courses", {"name": "Математика"}, 201)
        return await self.call("POST", "/sessions", {"course_id": course["id"], "model": "fake/test"}, 201)

    async def idle(self, stream, after=0):
        """Wait until the chat finished its operation (the event after `after`)."""
        return await stream.wait(lambda e: e["type"] == "busy" and e["busy"] is False, after)


async def make_env(tmp_path, auto_title):
    store = Store(tmp_path / "state")
    store.prefs.update(default_model="fake/test", auto_compact=False, providers={
        "fake": {"api": "chat", "base_url": "http://fake.invalid/v1",
                 "models": [{"id": "test", "tools": True, "context": 32768}]}})
    store.save()
    work = tmp_path / "work"
    work.mkdir()
    script, requests = [], []

    async def handler(request):
        requests.append(json.loads(request.content))
        item = script.pop(0)
        return await item(request) if callable(item) else item

    client = httpx.AsyncClient(transport=httpx.MockTransport(handler))
    service = Service(store, work, providers=Providers(store, client=client), auto_title=auto_title)
    app = make_app(service, TOKEN, [ORIGIN])
    async with TestClient(TestServer(app), headers={"Authorization": f"Bearer {TOKEN}"}) as http:
        yield Env(http, service, script, requests)
        await service.close()
    await client.aclose()


