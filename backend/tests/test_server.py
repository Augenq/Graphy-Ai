    assert state['style_presentation'] == style_presentation(runtime.session)
    await env.call('PUT', f'/sessions/{sid}/style', {'explanation_style': '../teacher'}, status=400)
    assert env.service.runtime(sid).session.explanation_style == 'socratic'


