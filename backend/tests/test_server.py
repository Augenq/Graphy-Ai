        assert prompt.count('# EXPLANATION STYLE:') == 1
        assert f'# EXPLANATION STYLE: {style.replace("_", " ").title()}' in prompt
        assert runtime.session.messages == []  # settings are not learner messages or evidence
        context = request_context(runtime.session, runtime.tools)
        state = json.loads(next(m['content'] for m in context if m['role'] == 'context').split('\n', 1)[1])
        assert state['style_method'] == style_method(runtime.session)
        assert state['style_presentation'] == style_presentation(runtime.session)
        assert 'Presentation:' not in state['style_method']
