async def test_explanation_style_replaces_prompt_and_survives_reopen(env):
    from reference_graphy.context import request_context, style_method, style_presentation, system_prompt

    lesson = await env.lesson()
    sid = lesson['id']
    assert lesson['explanation_style'] == 'deep_dive'
    runtime = env.service.runtime(sid)
    original = system_prompt(runtime.session, runtime.tools)
    assert '# ANTI-SLOP FRAMEWORK' in original
    assert '# EXPLANATION STYLE: Deep Dive' in original
    for style in ('quick_take', 'socratic', 'structured_reference', 'conversational_mentor', 'deep_dive'):
        changed = await env.call('PUT', f'/sessions/{sid}/style', {'explanation_style': style})
        assert changed['explanation_style'] == style
